#!/usr/bin/env python3
"""Restricted .atto scalar-to-native C++ compiler (prototype; no actor lowering)."""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

MAX_SOURCE_BYTES = 16384
MAX_TOKENS = 256
MAX_NODES = 128
MAX_DEPTH = 24
I64_MAX = (1 << 63) - 1
I64_MIN = -(1 << 63)
TOKEN = re.compile(r"(?P<space>\s+)|(?P<int>[0-9]+)|"
                   r"(?P<name>[A-Za-z_][A-Za-z0-9_]*)|(?P<punct>[(){}:;+\-*])")


class SourceError(ValueError):
    pass


def tokenize(source: str) -> list[str]:
    tokens = []
    index = 0
    while index < len(source):
        match = TOKEN.match(source, index)
        if match is None:
            raise SourceError(f"E_SOURCE: unsupported token at byte offset {index}")
        if match.lastgroup != "space":
            tokens.append(match.group())
            if len(tokens) > MAX_TOKENS:
                raise SourceError("E_SOURCE_LIMIT: too many tokens")
        index = match.end()
    return tokens


class Parser:
    def __init__(self, tokens: list[str]):
        self.tokens = tokens
        self.index = 0
        self.nodes = 0

    def peek(self) -> str | None:
        return self.tokens[self.index] if self.index < len(self.tokens) else None

    def take(self) -> str:
        value = self.peek()
        if value is None:
            raise SourceError("E_SYNTAX: unexpected end of source")
        self.index += 1
        return value

    def expect(self, word: str) -> None:
        if self.take() != word:
            raise SourceError(f"E_SYNTAX: expected {word}")

    def node(self, value: tuple):
        self.nodes += 1
        if self.nodes > MAX_NODES:
            raise SourceError("E_SOURCE_LIMIT: too many expression nodes")
        return value

    def parse(self):
        if self.peek() == "pub":
            self.take()
        for word in ("fnc", "main", "(", ")", ":", "int", "{", "return"):
            self.expect(word)
        expression = self.expr(0)
        for word in (";", "}"):
            self.expect(word)
        if self.peek() is not None:
            raise SourceError("E_SYNTAX: trailing tokens")
        return expression

    def expr(self, depth: int):
        lhs = self.term(depth + 1)
        while self.peek() in ("+", "-"):
            op = self.take()
            rhs = self.term(depth + 1)
            lhs = self.node((op, lhs, rhs))
        return lhs

    def term(self, depth: int):
        lhs = self.unary(depth + 1)
        while self.peek() == "*":
            self.take()
            rhs = self.unary(depth + 1)
            lhs = self.node(("*", lhs, rhs))
        return lhs

    def unary(self, depth: int):
        if depth > MAX_DEPTH:
            raise SourceError("E_SOURCE_LIMIT: expression nesting too deep")
        if self.peek() == "-":
            self.take()
            if self.peek() == "9223372036854775808":
                self.take()
                return self.node(("number", I64_MIN))
            return self.node(("neg", self.unary(depth + 1)))
        if self.peek() == "+":
            self.take()
            return self.unary(depth + 1)
        if self.peek() == "(":
            self.take()
            inside = self.expr(depth + 1)
            self.expect(")")
            return inside
        token = self.take()
        if not token.isascii() or not token.isdecimal() or len(token) > 19:
            raise SourceError("E_TYPE: expected decimal i64 literal")
        value = int(token)
        if value > I64_MAX:
            raise SourceError("E_RANGE: i64 literal out of range")
        return self.node(("number", value))


def compile_source(source: str) -> str:
    if len(source.encode("utf-8")) > MAX_SOURCE_BYTES:
        raise SourceError("E_SOURCE_LIMIT: source exceeds 16 KiB")
    root = Parser(tokenize(source)).parse()
    lines = [
        "// Generated by restricted Forge .atto scalar prototype.",
        '#include "atto/checked_i64.hpp"',
        "#include <cstdint>",
        "#include <iostream>",
        "#include <limits>",
        "int main() {",
    ]
    counter = 0

    def emit(node):
        nonlocal counter
        kind = node[0]
        if kind == "number":
            value = node[1]
            expr = ("std::numeric_limits<std::int64_t>::min()" if value == I64_MIN
                    else f"std::int64_t{{{value}LL}}")
            name = f"v{counter}"
            counter += 1
            lines.append(f"  const std::int64_t {name} = {expr};")
            return name
        if kind == "neg":
            left = "std::int64_t{0}"
            right = emit(node[1])
            method = "checked_sub"
        else:
            left = emit(node[1])
            right = emit(node[2])
            method = {"+": "checked_add", "-": "checked_sub", "*": "checked_mul"}[kind]
        ident = counter
        counter += 1
        lines.append(f"  const auto r{ident} = atto::forge::{method}({left}, {right});")
        lines.append(f'  if (!r{ident}) {{ std::cerr << "E_OVERFLOW\\n"; return 70; }}')
        lines.append(f"  const std::int64_t v{ident} = *r{ident};")
        return f"v{ident}"

    result = emit(root)
    lines.append(f"  std::cout << {result} << '\\n';")
    lines.extend(["  return 0;", "}", ""])
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        if args.source.stat().st_size > MAX_SOURCE_BYTES:
            raise SourceError("E_SOURCE_LIMIT: source exceeds 16 KiB")
        code = compile_source(args.source.read_text(encoding="utf-8"))
        args.output.write_text(code, encoding="utf-8", newline="\n")
    except (SourceError, OSError, UnicodeError) as error:
        print(f"Forge scalar compile error: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
